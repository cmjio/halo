/**
 * Write site/src/icons.ts: the Tabler icons (https://tabler.io/icons, MIT) the site and
 * the playground use, as inline SVG. Only the icons named here are copied, so the
 * playground doesn't ship the whole set. Studio uses @tabler/icons-react instead.
 *
 *   bun scripts/icons.ts
 *
 * To use another icon, add its name (as on tabler.io/icons) below and run this again.
 */

import { resolve } from "node:path";

const NAMES = [
  // Example sections (examples/catalog.ts)
  "seedling", "puzzle", "tool", "compass", "lock", "microscope", "message-circle", "trending-up", "coin", "scale", "stethoscope", "truck", "home",
  // Challenges (site/src/challenges.ts)
  "bug", "cash-banknote", "hand-stop", "bolt", "traffic-lights", "repeat", "palette",
  // Cheat sheet cards and plan steps
  "robot", "route", "arrow-right", "arrows-split", "shield", "link", "schema", "printer", "brain",
  // Everything else in the playground
  "dice-5", "target", "sparkles", "circle-check", "circle-dashed", "bulb", "eye", "confetti", "trophy", "wand", "mood-smile", "rotate",
].sort();

const root = resolve(import.meta.dir, "..");
const nodes: Record<string, Array<[string, Record<string, string>]>> = await Bun.file(resolve(root, "node_modules/@tabler/icons/tabler-nodes-outline.json")).json();
const { version } = await Bun.file(resolve(root, "node_modules/@tabler/icons/package.json")).json();

const body = NAMES.map((name) => {
  const n = nodes[name];
  if (!n) throw new Error(`No Tabler icon called "${name}"`);
  const inner = n.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(" ")}/>`).join("");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(inner)},`;
}).join("\n");

await Bun.write(
  resolve(root, "site/src/icons.ts"),
  `// Generated by scripts/icons.ts from @tabler/icons ${version} (MIT, https://tabler.io/icons). Don't edit by hand.

const ICONS = {
${body}
} as const;

export type IconName = keyof typeof ICONS;

/** A Tabler icon as inline SVG. It takes the text's color and is sized by the .ti class (1em by default). */
export function icon(name: IconName, label?: string): string {
  const a11y = label ? \`role="img" aria-label="\${label.replace(/"/g, "&quot;")}"\` : 'aria-hidden="true"';
  return \`<svg class="ti ti-\${name}" \${a11y} xmlns="http://www.w3.org/2000/svg" width="1em" height="1em" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\${ICONS[name]}</svg>\`;
}
`,
);
console.log(`wrote site/src/icons.ts (${NAMES.length} icons)`);
