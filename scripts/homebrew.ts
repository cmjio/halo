/**
 * Write the Homebrew formula for a release, so `brew install cmjio/halo/halolang` installs it.
 *
 *   bun scripts/homebrew.ts                 into dist/homebrew/Formula/halolang.rb, from dist/release/<version>/SHA256SUMS
 *   bun scripts/homebrew.ts --from <dir>    from the SHA256SUMS in another directory
 *   bun scripts/homebrew.ts --out <file>    somewhere else (CI writes straight into the tap's checkout)
 *
 * The formula lives in the tap repository, github.com/cmjio/homebrew-halo; the Release workflow
 * regenerates it there for every stable release (prereleases and nightlies stay off Homebrew).
 * It downloads the release's prebuilt binaries from the GitHub release and checks them against
 * SHA256SUMS. `halo` is installed behind a small wrapper that sets HALO_INSTALLED_BY=homebrew,
 * so `halo upgrade` sends people to `brew upgrade` instead of replacing a file brew owns.
 */

import { dirname, join, resolve } from "node:path";
import { mkdirSync } from "node:fs";
import pkg from "../package.json" with { type: "json" };

const REPO = "https://github.com/cmjio/halo";

/** The release files the formula uses, by Homebrew's OS and CPU blocks. Linux is glibc (Homebrew on Linux is). */
export const ASSETS = {
  mac: { arm: "halo-darwin-arm64", intel: "halo-darwin-x64" },
  linux: { arm: "halo-linux-arm64", intel: "halo-linux-x64" },
} as const;

/** `<sha>  <file>` lines, as scripts/release.ts writes them, to a file → sha map. */
export function parseSums(text: string): Record<string, string> {
  const sums: Record<string, string> = {};
  for (const line of text.split("\n")) {
    const m = line.trim().match(/^([0-9a-f]{64})\s+\*?(\S+)$/);
    if (m) sums[m[2]!] = m[1]!;
  }
  return sums;
}

export function formula(version: string, sums: Record<string, string>): string {
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`Homebrew gets stable releases only, not ${version}`);
  const block = (file: string) => {
    const sha = sums[file];
    if (!sha) throw new Error(`No ${file} in SHA256SUMS`);
    return [`      url "${REPO}/releases/download/v${version}/${file}"`, `      sha256 "${sha}"`].join("\n");
  };
  const os = (name: "mac" | "linux") =>
    [
      `  on_${name === "mac" ? "macos" : "linux"} do`,
      `    on_arm do`,
      block(ASSETS[name].arm),
      `    end`,
      `    on_intel do`,
      block(ASSETS[name].intel),
      `    end`,
      `  end`,
    ].join("\n");

  return `# Generated by scripts/homebrew.ts in ${REPO} for each release; edits here are overwritten.
class Halolang < Formula
  desc "Declarative language for AI workflows"
  homepage "https://halolang.com"
  license "MIT"

${os("mac")}

${os("linux")}

  def install
    # The download is the bare binary, named for its platform.
    libexec.install Dir["halo-*"].first => "halo"
    chmod 0755, libexec/"halo"
    # \`halo upgrade\` reads this and points at \`brew upgrade\` instead of replacing the binary.
    (bin/"halo").write_env_script libexec/"halo", HALO_INSTALLED_BY: "homebrew"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/halo --version").strip
    system bin/"halo", "init", "demo"
    assert_path_exists testpath/"demo/main.halo"
  end
end
`;
}

if (import.meta.main) {
  const root = resolve(import.meta.dir, "..");
  const argv = process.argv.slice(2);
  const opt = (name: string) => {
    const i = argv.indexOf(name);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  const version = pkg.version;
  const from = resolve(root, opt("--from") ?? join("dist/release", version));
  const out = resolve(root, opt("--out") ?? "dist/homebrew/Formula/halolang.rb");
  const sumsFile = Bun.file(join(from, "SHA256SUMS"));
  if (!(await sumsFile.exists())) throw new Error(`No SHA256SUMS in ${from}. Build the release first (bun scripts/release.ts --no-upload).`);
  mkdirSync(dirname(out), { recursive: true });
  await Bun.write(out, formula(version, parseSums(await sumsFile.text())));
  console.log(`Wrote ${out} (halolang ${version})`);
}
