// ── Registry HTTP API ──
//
// A registry has a base URL (or, for a static registry, a folder). Every path below is
// relative to it. Static registries serve the GET paths as files; the service serves all.
//
//   GET    v1/index.json                                  every package: PackageSummary[] (static registries; the service too)
//   GET    v1/search?q=&limit=&offset=                    SearchResponse (service only)
//   GET    v1/packages/@scope/name.json                   PackageDoc
//   GET    v1/files/@scope/name/<version>.halotool        the package file (immutable)
//   GET    v1/packages/@scope/name/stats?days=30          PackageStats: downloads and dependents (service only)
//   PUT    v1/packages/@scope/name                        publish: body = package file bytes, Content-Type PACKAGE_MEDIA_TYPE → 201 PublishResponse
//   POST   v1/packages/@scope/name/versions/<v>/yank      { reason } → 200
//   DELETE v1/packages/@scope/name/versions/<v>/yank      unyank → 200
//   POST   v1/packages/@scope/name/deprecate              { range, message } (empty message clears) → 200
//   PUT    v1/packages/@scope/name/dist-tags/<tag>        { version } → 200 DistTagsResponse
//   DELETE v1/packages/@scope/name/dist-tags/<tag>        → 200 DistTagsResponse ("latest" can't be removed)
//   POST   v1/auth/device                                 DeviceStart
//   POST   v1/auth/device/token                           { device_code } → 200 TokenResponse | 428 authorization_pending | 429 slow_down | 410 expired_token
//   GET    v1/whoami                                      WhoAmI
//   GET    v1/tokens                                      TokenList
//   POST   v1/tokens                                      CreateTokenRequest → 201 CreatedToken (the secret is shown once)
//   DELETE v1/tokens/<id>                                 → 200 { deleted: id } (a full token, or the token revoking itself)
//   POST   v1/scopes                                      { scope } → 201 ScopeDoc (creates an org scope; you become its owner; needs a full token)
//   GET    v1/scopes/@scope                               ScopeDoc
//   PUT    v1/scopes/@scope/members/<login>               { role } → 200 ScopeDoc ; DELETE removes → 200 ScopeDoc
//   POST   v1/scopes/@scope/verify                        { domain } → VerifyResponse
//
// Writes need `Authorization: Bearer <token>`. Errors are ApiError JSON with a 4xx/5xx status.
// A publish body is at most MAX_PACKAGE_WIRE_BYTES (413 above it). Yank and unyank answer
// YankResponse; deprecate answers DeprecateResponse.
// Package pages (HTML) are served at /@scope/name and /@scope/name/v/<version>.

export const API_PREFIX = "v1";

export function packageDocPath(name: string): string {
  const p = mustName(name);
  return `${API_PREFIX}/packages/${p.scope}/${p.name}.json`;
}

export function packageFilePath(name: string, version: string): string {
  const p = mustName(name);
  return `${API_PREFIX}/files/${p.scope}/${p.name}/${version}.halotool`;
}

export function packageApiPath(name: string): string {
  const p = mustName(name);
  return `${API_PREFIX}/packages/${p.scope}/${p.name}`;
}

export const INDEX_PATH = `${API_PREFIX}/index.json`;

function mustName(name: string): PackageName {
  const p = parsePackageName(name);
  if (!p) throw new ManifestError(`"${name}" is not a scoped package name like @acme/support-kit`);
  return p;
}

