/** v2 package files. v1 (`halo-tool/1`, halo-tool.json) stays readable. */
export const PACKAGE_FORMAT_V2 = "halo-package/2";
export const PACKAGE_MEDIA_TYPE = "application/vnd.halo.package+json";
/** The cap on a package's files, raw (before base64), as `halo pack` adds them up. */
export const MAX_PACKAGE_BYTES = 5 * 1024 * 1024;
/**
 * The cap on a package file on the wire: the encoded JSON (`PackageFileV2`) that `halo publish`
 * sends and the registry stores. Base64 makes files 4/3 bigger, and the JSON adds paths, the
 * manifest and hosted interfaces, so a package just under MAX_PACKAGE_BYTES still fits.
 */
export const MAX_PACKAGE_WIRE_BYTES = 8 * 1024 * 1024;
/** Never packed: local state, secrets, other packages. */
export const PACK_EXCLUDE = [/^node_modules\//, /^\.halo\//, /^\.git\//, /\.halotool$/, /^halo\.lock$/, /(^|\/)\.env(\..*)?$/, /^\.dev\.vars$/, /(^|\/)package-keys\.json$/];

/** What a hosted pipeline looks like from outside. Written by `halo publish`; the source is not shipped. */
export interface HostedPipelineInterface {
  description?: string;
  params: { name: string; type: string }[];
  returns?: string;
  /** Schemas its params and return type use, as Halo schema declarations' fields. */
  schemas?: Record<string, Record<string, string>>;
  /** The tool calls it can make on the publisher's side, as `halo plan` computed them ("Desk.add_comment", "write"). */
  effects?: { target: string; effect: string }[];
}

/** Why a hosted interface (from a package file) isn't the right shape; empty when it is. */
export function hostedInterfaceProblems(name: string, iface: unknown): string[] {
  const out: string[] = [];
  const bad = (m: string) => out.push(`hosted: ${name}: ${m}`);
  const isStr = (x: unknown) => typeof x === "string";
  if (!iface || typeof iface !== "object" || Array.isArray(iface)) return [`hosted: ${name}: the interface must be an object`];
  const i = iface as Record<string, unknown>;
  if (i.description !== undefined && !isStr(i.description)) bad("description must be a string");
  if (!Array.isArray(i.params) || i.params.some((p) => !p || typeof p !== "object" || !isStr((p as { name?: unknown }).name) || !isStr((p as { type?: unknown }).type)))
    bad("params must be a list of { name, type } strings");
  if (i.returns !== undefined && !isStr(i.returns)) bad("returns must be a type, as a string");
  if (i.schemas !== undefined) {
    const s = i.schemas;
    if (!s || typeof s !== "object" || Array.isArray(s) || Object.values(s).some((f) => !f || typeof f !== "object" || Array.isArray(f) || Object.values(f).some((t) => !isStr(t))))
      bad("schemas must map schema names to { field: type } objects");
  }
  if (i.effects !== undefined && (!Array.isArray(i.effects) || i.effects.some((e) => !e || typeof e !== "object" || !isStr((e as { target?: unknown }).target) || !isStr((e as { effect?: unknown }).effect))))
    bad("effects must be a list of { target, effect } strings");
  return out;
}

