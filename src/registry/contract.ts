/**
 * Check a package's halo.json. `files`, when given, is the set of paths in the package, so
 * exports and the README can be checked too. Throws ManifestError listing every problem.
 */
export function checkPackageManifest(raw: unknown, options: { files?: Iterable<string>; reservedProviders?: Iterable<string> } = {}): PackageManifest {
  const problems: string[] = [];
  const bad = (m: string) => problems.push(m);
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) throw new ManifestError(`${PROJECT_FILE} must be a JSON object`);
  const m = raw as PackageManifest;
  const files = options.files ? new Set(options.files) : undefined;

  if (typeof m.name !== "string" || !parsePackageName(m.name)) bad(`name must be a scoped name like "@acme/support-kit" (got ${JSON.stringify(m.name)})`);
  // Exactly one spelling per version: no "v1.0.0", " 1.0.0" or "1.0.0+build", which would
  // otherwise be a second, different key for a version that's already published.
  if (typeof m.version !== "string" || !isValidVersion(m.version)) bad(`version must be semver, like 1.2.3 (got ${JSON.stringify(m.version)})`);
  else if (!isCanonicalVersion(m.version)) bad(`version must be written as MAJOR.MINOR.PATCH[-PRERELEASE], with no leading "v", spaces or build metadata ("+..."): ${JSON.stringify(m.version)}`);
  if (typeof m.description !== "string" || !m.description.trim()) bad("description is required");
  if (m.halo !== undefined && (typeof m.halo !== "string" || !isValidRange(m.halo))) bad(`halo must be a version range, like ">=0.9.0"`);
  if (m.keywords !== undefined && (!Array.isArray(m.keywords) || m.keywords.some((k) => typeof k !== "string" || !k.trim()))) bad("keywords must be a list of strings");
  for (const key of ["license", "repository", "homepage"] as const) if (m[key] !== undefined && typeof m[key] !== "string") bad(`${key} must be a string`);

  if (m.exports !== undefined) {
    if (!Array.isArray(m.exports)) bad("exports must be a list of .halo files");
    else
      for (const path of m.exports) {
        if (typeof path !== "string" || !safeRelative(path) || !path.endsWith(".halo")) bad(`exports: "${path}" must be a .halo file inside the package`);
        else if (files && !files.has(path)) bad(`exports: ${path} is not in the package`);
      }
  }
  if (m.models !== undefined) {
    if (typeof m.models !== "object" || Array.isArray(m.models)) bad("models must map slot names to { description, suggested }");
    else
      for (const [slot, spec] of Object.entries(m.models)) {
        if (!SLOT.test(slot)) bad(`models.${slot}: slot names start with a lowercase letter and use letters, digits and _`);
        if (!spec || typeof spec !== "object" || typeof spec.description !== "string" || !spec.description.trim()) bad(`models.${slot}.description is required (consumers read it to pick a model)`);
        else if (spec.suggested !== undefined && typeof spec.suggested !== "string") bad(`models.${slot}.suggested must be a model id`);
      }
  }
  if (m.providers !== undefined) checkProviders(m.providers, options.reservedProviders ?? [], bad, { required: false });
  if (m.skills !== undefined && (typeof m.skills !== "string" || !safeRelative(m.skills.replace(/\/+$/, "")))) bad("skills must be a folder inside the package");
  if (m.env !== undefined && (!Array.isArray(m.env) || m.env.some((e) => typeof e !== "string" || !ENV.test(e)))) bad("env must list environment variable names");
  if (m.dependencies !== undefined) {
    if (typeof m.dependencies !== "object" || Array.isArray(m.dependencies)) bad("dependencies must map package names to version ranges");
    else
      for (const [dep, range] of Object.entries(m.dependencies)) {
        if (!parsePackageName(dep)) bad(`dependencies: "${dep}" is not a scoped package name`);
        if (dep === m.name) bad("a package can't depend on itself");
        if (typeof range !== "string" || !isValidRange(range)) bad(`dependencies.${dep}: "${range}" is not a version range`);
      }
  }
  if (m.hosted !== undefined) {
    const h = m.hosted;
    if (!h || typeof h !== "object") bad("hosted must be an object");
    else {
      if (typeof h.endpoint !== "string" || !isHttps(h.endpoint)) bad("hosted.endpoint must be an https URL (http only for localhost)");
      if (!Array.isArray(h.exports) || !h.exports.length || h.exports.some((p) => typeof p !== "string" || !PIPELINE.test(p))) bad("hosted.exports must list pipeline names");
      if (!h.auth || typeof h.auth !== "object") bad(`hosted.auth is required: halo serve --package only answers consumers with a key, e.g. "auth": { "type": "bearer", "env": "ACME_HALO_KEY" }`);
      else {
        if (h.auth.type !== "bearer" && h.auth.type !== "header") bad("hosted.auth.type must be bearer or header");
        if (typeof h.auth.env !== "string" || !ENV.test(h.auth.env)) bad("hosted.auth.env must name an environment variable");
        else if (isReservedAuthEnv(h.auth.env)) bad(`hosted.auth.env can't be ${h.auth.env}: that's one of the consumer's other secrets, and its value would go to ${typeof h.endpoint === "string" ? h.endpoint : "the endpoint"}. Name a variable for your key only, like ACME_HALO_KEY`);
        if (h.auth.type === "header" && !h.auth.name) bad("hosted.auth.name is required for header auth");
      }
    }
  }
  const hasContent = !!(m.exports?.length || (m.providers && Object.keys(m.providers).length) || m.skills || m.hosted);
  if (!hasContent) bad("a package must export something: exports, providers, skills, or hosted");
  if (files && !files.has(README_FILE)) bad(`${README_FILE} is required: it's the package's page in the registry`);

  if (problems.length) throw new ManifestError(`Invalid ${PROJECT_FILE}${typeof m.name === "string" ? ` for "${m.name}"` : ""}:\n  - ${problems.join("\n  - ")}`);
  return m;
}

/**
 * Why a hosted endpoint isn't an ordinary public https server, or undefined when it is: plain
 * http, this machine, or a private-network address. The public registry refuses these; a
 * folder registry may not, so `halo add` and `halo install` warn about them.
 */
export function hostedEndpointConcern(endpoint: string): string | undefined {
  let u: URL;
  try {
    u = new URL(endpoint);
  } catch {
    return "isn't a valid URL";
  }
  // A trailing dot (`localhost.`) names the same host.
  const host = u.hostname.toLowerCase().replace(/^\[|\]$/g, "").replace(/\.+$/, "");
  const loopback = host === "localhost" || host.endsWith(".localhost") || /^127\./.test(host) || host === "::1" || host === "0.0.0.0" || host === "::";
  const v4 = host.match(/^(\d+)\.(\d+)\.\d+\.\d+$/);
  const [a, b] = v4 ? [Number(v4[1]), Number(v4[2])] : [NaN, NaN];
  const privateNet =
    a === 10 || (a === 172 && b >= 16 && b <= 31) || (a === 192 && b === 168) || (a === 169 && b === 254) || (a === 100 && b >= 64 && b <= 127) ||
    /^f[cd][0-9a-f]{2}:/.test(host) || /^fe[89ab][0-9a-f]:/.test(host) || host.startsWith("::ffff:") ||
    host.endsWith(".local") || host.endsWith(".internal") || host.endsWith(".lan") || (!host.includes(".") && !host.includes(":"));
  const where = loopback ? "this machine" : privateNet ? "a private network address" : undefined;
  if (u.protocol === "http:") return `uses plain http${where ? ` to ${where}` : ""}`;
  if (u.protocol !== "https:") return `uses ${u.protocol.replace(/:$/, "")}, not https`;
  return where ? `points at ${where}` : undefined;
}

function isHttps(url: string): boolean {
  try {
    const u = new URL(url);
    return u.protocol === "https:" || (u.protocol === "http:" && ["localhost", "127.0.0.1", "[::1]"].includes(u.hostname));
  } catch {
    return false;
  }
}

