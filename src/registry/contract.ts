// ── Hosted pipelines: the wire protocol ──
//
// The consumer's runtime calls a hosted pipeline as:
//   POST <endpoint>/api/pipelines/<Pipeline>/runs
//   Halo-Package: @acme/support-kit@1.2.0
//   Authorization: Bearer <key>             (or the hosted.auth header)
//   { "args": { ... }, "wait": true }
// and reads { runId, status, output } as `halo serve` already returns. A server that no
// longer serves that package version answers 410 with an ApiError.

export const HOSTED_PACKAGE_HEADER = "Halo-Package";

// ── Lockfile v2 ──

export const LOCK_FILE = "halo.lock";
export const PACKAGES_DIR = ".halo/packages";

export interface LockPackage {
  version: string;
  /** "registry:default", "registry:<base url or folder>", a .halotool URL or path, or a folder (relative to the project). */
  source: string;
  sha256: string;
  /** The exact versions this package's dependencies resolved to. */
  dependencies: Record<string, string>;
  permissions: PackagePermissions;
  /** In the project's own halo.json dependencies (not only pulled in by another package). */
  direct: boolean;
}

export interface LockfileV2 {
  lockfileVersion: 2;
  packages: Record<string, LockPackage>;
}

// ── How the linker finds installed packages ──

export interface ResolvedPackage {
  name: string;
  version: string;
  /** Absolute path of the installed, checksum-verified package folder. */
  dir: string;
  manifest: PackageManifest;
  hosted?: Record<string, HostedPipelineInterface>;
}

export interface PackageResolver {
  /**
   * The package a `use "<name>"` refers to. `from` is the package doing the `use`
   * (undefined for the project itself); a package may only use its own declared dependencies.
   */
  resolve(name: string, from?: ResolvedPackage): ResolvedPackage | undefined;
}
